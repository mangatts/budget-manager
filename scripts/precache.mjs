// Keeps the offline file list in sw.js in sync with the app's files.
//   npm run precache          rewrite the list + version in sw.js
//   (tests/pwa.test.js fails CI if sw.js is out of date)
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SW = join(ROOT, 'sw.js');
const DIRS = ['css', 'js', 'fonts', 'icons'];
const EXTENSIONS = /\.(css|js|woff2|png)$/;
const START = '// <precache>';
const END = '// </precache>';

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

// Every file the app needs offline, as "./path" relative to the site root, sorted.
export function appFiles(root = ROOT) {
  const files = DIRS.flatMap((dir) => walk(join(root, dir))).filter((f) => EXTENSIONS.test(f));
  return ['index.html', 'manifest.json', ...files.map((f) => relative(root, f).split(sep).join('/'))].sort().map((f) => `./${f}`);
}

// Version = hash of every cached file's contents, so any change ships a new cache.
export function precacheBlock(root = ROOT) {
  const files = appFiles(root);
  const hash = createHash('sha256');
  for (const f of files) hash.update(f).update(readFileSync(join(root, f)));
  const version = hash.digest('hex').slice(0, 12);
  return [
    `${START} generated by \`npm run precache\`; do not edit by hand`,
    `const VERSION = '${version}';`,
    `const PRECACHE = [`,
    ...files.map((f) => `  '${f}',`),
    `];`,
    END,
  ].join('\n');
}

export function currentBlock() {
  const sw = readFileSync(SW, 'utf8');
  return sw.slice(sw.indexOf(START), sw.indexOf(END) + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const sw = readFileSync(SW, 'utf8');
  writeFileSync(SW, sw.replace(currentBlock(), precacheBlock()));
  console.log(`sw.js: ${appFiles().length} files, ${precacheBlock().match(/VERSION = '(\w+)'/)[1]}`);
}
